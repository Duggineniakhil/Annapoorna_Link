export type TKey = Key;

interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: Key, vars?: Record<string, string | number>) => string;
  pick: (b: Bilingual | { en: string; te: string }) => string;
}

const Ctx = createContext<I18n | null>(null);
const LANG_KEY = "al2.lang";

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      return localStorage.getItem(LANG_KEY) === "te" ? "te" : "en";
    } catch {
      return "en";
    }
  });
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(LANG_KEY, l);
    } catch {
      /* not saved; still switches for this visit */
    }
  }, []);
  const value = useMemo<I18n>(() => {
    const dict = lang === "te" ? te : en;
    return {
      lang,
      setLang,
      t: (key, vars) => dict[key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars?.[k] ?? "")),
      pick: (b) => (lang === "te" ? b.te : b.en),
    };
  }, [lang, setLang]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useT(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error("useT outside LangProvider");
  return v;
}

export const dictionaries = { en, te };
